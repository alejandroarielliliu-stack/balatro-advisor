const fixture = () => success(parseState(readFileSync(new URL('../../examples/shop-purchase.json', import.meta.url), 'utf8')));
const mutation = (s: GameState) => ({ expectedRevision: s.revision, updatedAt: '2026-10-09T18:00:00Z' });
const hand = { cardIds: ['8S','8H'], discardsRemaining: 3 };
function j(id: string, sell = 2, green = 0): JokerInstance {
  return { instanceId: id, catalogId: id, edition: known('base'), stickers: known([]), sellValue: known(sell),
    counters: id === 'green_joker' ? { greenMult: known(green) } : {} };
}
function withJokers(...ids: string[]): GameState { const s = fixture(); s.observed.jokers = known(ids.map(id => j(id, id === 'joker' ? 1 : id === 'golden_joker' ? 3 : 2))); return s; }
function rejects<T>(result: EngineResult<T>, code: string) {
  assert.ok(!result.ok, JSON.stringify(result)); assert.equal(result.errors[0]?.code, code); assert.ok(result.errors[0]?.message);
}
function boss(s: GameState, id: string, ante: number, target: number, reward = 5) {
  s.observed.nextBlind = known({ ante, kind: 'boss', bossId: known(id), target: known(target), reward: known(reward) });
}
function small(s: GameState, ante = 1, target = 300) {
  s.observed.nextBlind = known({ ante, kind: 'small', bossId: known('none'), target: known(target), reward: known(3) });
}

