test('RUN01a leer y preparar migración no escriben; respaldo conserva los bytes originales',()=>{
  const {memory,raw,record,store}=setupLegacy();
  assert.deepEqual(success(store.load()),record);assert.equal(memory.writes,0);
  const prepared=success(store.prepareMigration());
  assert.equal(prepared.expectedRaw,raw);assert.equal(prepared.requiresMigration,true);assert.deepEqual(prepared.record,expectedRecord(record));
  assert.equal(memory.writes,0);assert.equal(memory.getItem(CONFIRMED_STORAGE_KEY),raw);
  const saved=success(store.migrateToCurrent({confirmed:true,expectedRaw:prepared.expectedRaw}));
  assert.deepEqual(saved,expectedRecord(record));assert.deepEqual(success(createConfirmedStore(()=>memory).load()),saved);
  assert.equal(success(store.exportMigrationBackup()),raw);assert.equal(saved.state.revision,record.state.revision);
  const recovery=new MemoryStorage();
  assert.deepEqual(success(createConfirmedStore(()=>recovery).restoreJson(success(store.exportMigrationBackup()),{confirmed:true,expectedRaw:null})),record);
  const rawAfter=memory.getItem(CONFIRMED_STORAGE_KEY),writes=memory.writes;
  assert.equal(success(store.prepareMigration()).requiresMigration,false);
  assert.deepEqual(success(store.migrateToCurrent({confirmed:true,expectedRaw:rawAfter!})),saved);
  assert.equal(memory.writes,writes);assert.equal(success(store.exportMigrationBackup()),raw);
});

