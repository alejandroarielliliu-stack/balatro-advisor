const expectedState=(state:LegacyState)=>({...structuredClone(state),schemaVersion:'0.2',phaseData:{origin:{status:'unknown',reason:'La partida 0.1 no registra qué ciega originó esta tienda.'}}});
const expectedRecord=(record:ReturnType<typeof legacyHistory>)=>({...structuredClone(record),schemaVersion:'confirmed-2',initialState:expectedState(record.initialState),state:expectedState(record.state),history:record.history.map(entry=>({...structuredClone(entry),before:expectedState(entry.before),after:expectedState(entry.after)}))});
function setupLegacy(record=legacyHistory()) {
  const memory=new MemoryStorage(),raw=JSON.stringify(record,null,2)+'\n';memory.values.set(CONFIRMED_STORAGE_KEY,raw);
  return {memory,raw,record,store:createConfirmedStore(()=>memory)};
}

