  const shop=migrated.state.observed.shop;
  assert.equal(shop.status,'known');
  if(shop.status==='known')assert.equal(errorCode(createShopSessionStore(()=>memory).observeJokerOffers({
    ...header(migrated.state,'stale-no-op'),expected:oldBinding,shopId:shop.value.shopId,offers:shop.value.cardOffers
  })),'stale_revision');
  assert.equal(memory.writes,writes);assert.equal(memory.getItem(CONFIRMED_STORAGE_KEY),currentRaw);
